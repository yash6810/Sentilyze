    r"G:\My Drive\Sentilyze_GPU_Artifacts",
    r"G:\MyDrive\Sentilyze_GPU_Artifacts",
    os.path.expanduser(r"~\Google Drive\Sentilyze_GPU_Artifacts"),
    os.path.expanduser(r"~\My Drive\Sentilyze_GPU_Artifacts"),
